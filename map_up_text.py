def run_candidate_pipeline(hypothesis_list: List[TokenHypotheses], llm_elements: List[LLMToken]) -> List[TokenHypotheses]:
    hypothesis_list = assign_llm_candidates_to_all_token_hypotheses_by_fuzzy_matching(hypothesis_list, llm_elements) # assign possible llm elements to all token hypotheses based onnly on fuzzy matching of each individual word. Doesn't consider context.
    # Process each hypothesis individually since assign_llm_candidates_to_all_token_hypotheses_by_context takes a single TokenHypotheses
    for hypothesis in hypothesis_list:
        assign_llm_candidates_to_all_token_hypotheses_by_context(hypothesis)
    hypothesis_list = narrow_hypothesis_token_candidates_by_context(hypothesis_list) # narrow down the list of token candidates by context based on the before and after alto words.
    hypothesis_list = find_best_candidates_for_all_hypothesis_objects(hypothesis_list, llm_elements) # find the best candidates for all hypothesis objects.
    hypothesis_list = link_hypothesis_objects_by_context(hypothesis_list) # link hypothesis objects by context based on the chosen_LLM_token.w_after and chosen_LLM_token.w_before.
    return hypothesis_list


def run_one_iteration(
    hypothesis_list: List[TokenHypotheses],
    llm_elements: List[LLMToken],
    page: XMLOBJ.Page
) -> List[TokenHypotheses]:
    """
    Run one iteration of the pipeline: hyphen linking, word merges, reference updates, context matching.
    Returns the updated hypothesis list.
    """
    # First, split hyphenated triplets (ALTO "assignment-his" → clean "assignment" "-" "his")
    # This must happen BEFORE hyphen linking to avoid conflicts
    hypothesis_list = split_hyphenated_triplets(hypothesis_list, llm_elements)
    
    # Link hyphen pairs (for word-wrap hyphens and other combinations)
    hypothesis_list = link_hyphen_pairs(hypothesis_list, llm_elements, page)
    
    # Re-run context matching (using helper function to consolidate repeated pattern)
    hypothesis_list = _rerun_context_matching_pipeline(hypothesis_list, llm_elements)
    
    # Search for word merges
    hypothesis_list = search_for_word_merges(hypothesis_list, llm_elements)
    
    # Update before_word/after_word references for split words
    current_anchors = {id(hyp.anchor): hyp.anchor for hyp in hypothesis_list}
    content_to_hypotheses = {}
    for hyp in hypothesis_list:
        content = hyp.anchor.content
        if content not in content_to_hypotheses:
            content_to_hypotheses[content] = []
        content_to_hypotheses[content].append(hyp)
        if hyp.candidates:
            for cand in hyp.candidates:
                for alto_word in cand.alto_words:
                    cand_content = alto_word.content
                    if cand_content not in content_to_hypotheses:
                        content_to_hypotheses[cand_content] = []
                    content_to_hypotheses[cand_content].append(hyp)
    
    for hyp in hypothesis_list:
        anchor = hyp.anchor
        if anchor.before_word is not None and id(anchor.before_word) not in current_anchors:
            original_content = anchor.before_word.content
            if original_content in content_to_hypotheses:
                matching_hyps = content_to_hypotheses[original_content]
                if matching_hyps:
                    anchor.before_word = matching_hyps[-1].anchor
            else:
                from text_utils import decode_html_entities
                decoded = decode_html_entities(original_content)
                split_parts = ADVANCED_SPLIT_RE.split(decoded)
                if len(split_parts) > 1:
                    last_part = split_parts[-1].strip()
                    if last_part:
                        for other_hyp in hypothesis_list:
                            if other_hyp.anchor.content.strip() == last_part:
                                anchor.before_word = other_hyp.anchor
                                break
        
        if anchor.after_word is not None and id(anchor.after_word) not in current_anchors:
            original_content = anchor.after_word.content
            if original_content in content_to_hypotheses:
                matching_hyps = content_to_hypotheses[original_content]
                if matching_hyps:
                    anchor.after_word = matching_hyps[0].anchor
            else:
                from text_utils import decode_html_entities
                decoded = decode_html_entities(original_content)
                split_parts = ADVANCED_SPLIT_RE.split(decoded)
                if len(split_parts) > 1:
                    first_part = split_parts[0].strip()
                    if first_part:
                        for other_hyp in hypothesis_list:
                            if other_hyp.anchor.content.strip() == first_part:
                                anchor.after_word = other_hyp.anchor
                                break
    
    # Re-run context matching with updated references (using helper function)
    hypothesis_list = _rerun_context_matching_pipeline(hypothesis_list, llm_elements)
    
    return hypothesis_list


def run_iterative_pipeline(
    hypothesis_list: List[TokenHypotheses],
    llm_elements: List[LLMToken],
    page: XMLOBJ.Page,
    max_iterations: int = 5
) -> List[TokenHypotheses]:
    """
    Run the pipeline iteratively until stable (no changes) or max_iterations reached.
    Convergence is reached when matched_count, error_count, AND pending_count all remain static.
    """
    prev_matched_count = 0
    prev_error_count = 0
    prev_pending_count = 0
    
    for iteration in range(max_iterations):
        # Count current state
        current_matched = sum(1 for h in hypothesis_list if h.chosen_LLM_token)
        current_errors = sum(1 for h in hypothesis_list if h.flagged_for_error)
        current_pending = sum(1 for h in hypothesis_list if paragraph_reordering.is_pending_word(h))
        
        # Run one iteration
        hypothesis_list = run_one_iteration(hypothesis_list, llm_elements, page)
        
        # Count new state
        new_matched = sum(1 for h in hypothesis_list if h.chosen_LLM_token)
        new_errors = sum(1 for h in hypothesis_list if h.flagged_for_error)
        new_pending = sum(1 for h in hypothesis_list if paragraph_reordering.is_pending_word(h))
        
        # Check if stable (all three metrics unchanged)
        if (new_matched == prev_matched_count and 
            new_errors == prev_error_count and 
            new_pending == prev_pending_count):
            print(f"\nPipeline converged after {iteration + 1} iterations")
            break
        
        prev_matched_count = new_matched
        prev_error_count = new_errors
        prev_pending_count = new_pending
        print(f"Iteration {iteration + 1}: Matched: {new_matched}, Errors: {new_errors}, PENDING: {new_pending}")
    
    return hypothesis_list


