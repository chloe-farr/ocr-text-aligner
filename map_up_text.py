    print("\n" + "="*70)
    print("PIPELINE SUMMARY")
    print("="*70)
    
    # Print before/after summary stats
    print(f"\nBEFORE Processing:")
    print(f"  Matched words: {initial_matched}")
    print(f"  Error words: {initial_errors}")
    print(f"  PENDING words: {initial_pending}")
    
    print(f"\nAFTER Processing:")
    print(f"  Matched words: {final_matched} ({final_matched - initial_matched:+d})")
    print(f"  Error words: {final_errors} ({final_errors - initial_errors:+d})")
    print(f"  PENDING words: {final_pending} ({final_pending - initial_pending:+d})")
    
    # List unmatched ALTO words (failed to match)
    unmatched_words = []
    for hyp in hypothesis_list:
        if hyp.chosen_LLM_token is None:
            decoded = text_utils.decode_html_entities(hyp.anchor.content)
            unmatched_words.append(decoded)
    
