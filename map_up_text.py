def create_LLM_element_list(llm_clean_text: str) -> List[LLMToken]:
    """
    Creates a list of LLM tokens from the clean text.
    set values for word, word_normalized, w_before and w_after for each LLM token.
    """
    tokens = llm_clean_text.split()
    llm_elements: List[LLMToken] = []

    i = 0
    while i < len(tokens):
        word = tokens[i]
        word_normalized = text_utils.normalize_for_matching(word) #removes special characters and whitespace, but not hyphens
        llm_element_before = llm_elements[i-1] if i-1 >= 0 and len(llm_elements) > 0 else None 
        
        llm_element = LLMToken(word=word, word_normalized=word_normalized, w_before=llm_element_before)

        llm_elements.append(llm_element)
        # Set w_after on the previous element now that it's appended
        if i > 0 and len(llm_elements) > 1:
            llm_elements[i-1].w_after = llm_element
        i += 1

    if len(llm_elements) > 0:
        llm_elements[-1].w_after = None # last element has no w_after element

    return llm_elements

def create_hypothesis_list(
    alto_words: List[XMLOBJ.StringWord], 
    clean_vocab: set[str],
    fuzzy_cutoff: float = 80.0
) -> List[TokenHypotheses]:
    """
    Creates a list of TokenHypotheses from the alto words.
    Assigns possible word candidates to each TokenHypotheses object.
    - each fuzzy match above cutoff is a possible token candidate.
    - each token candidate is a possible interpretation of the alto word.
    
    Args:
        alto_words: List of ALTO StringWord objects
        clean_vocab: Set of normalized vocabulary words
        fuzzy_cutoff: Minimum fuzzy match score threshold (default: 80.0)
    
    Returns: List[TokenHypotheses] with candidates set.
    """
    hypothesis_list: List[TokenHypotheses] = []
    for alto_word in alto_words:
        # Initialize logical neighbors from ALTO spatial neighbors
        token_hypothesis_object = TokenHypotheses(
            anchor=alto_word,
            anchor_left=alto_word.before_word,  # Initialize from ALTO spatial neighbor
            anchor_right=alto_word.after_word   # Initialize from ALTO spatial neighbor
        )
        # Decode HTML entities in ALTO word content before fuzzy matching
        decoded_content = text_utils.decode_html_entities(alto_word.content)
        # Normalize the content for matching (removes punctuation, lowercases)
        normalized_content = text_utils.normalize_for_matching(decoded_content)
        
        # First check for exact match in normalized vocab
        if normalized_content in clean_vocab:
            token_hypothesis_object.candidates.append(
                TokenCandidate(clean_form=normalized_content, kind="word", alto_words=[alto_word], fuzzy_score=100.0)
            )
        else:
            # If no exact match, try fuzzy matching
            # Use a lower threshold to catch spelling errors like "Hanol" → "Hanoi" (80% match)
            # These will still go through context matching to ensure correct selection
            token_candidates = fuzzy_match_rapid(normalized_content, clean_vocab, cutoff=fuzzy_cutoff, limit=None)
            for token_candidate in token_candidates:
                token_hypothesis_object.candidates.append(TokenCandidate(clean_form=token_candidate[0], kind="word", alto_words=[alto_word], fuzzy_score=token_candidate[1]))
        hypothesis_list.append(token_hypothesis_object)
    return hypothesis_list

def analyze_ocr_accuracy(hypothesis_list: List[TokenHypotheses], show: bool = True) -> None:
    """
    Analyze OCR accuracy at the very beginning (before any processing).
    Shows breakdown of words by fuzzy match percentage.
    
    Args:
        hypothesis_list: List of TokenHypotheses after initial fuzzy matching
        show: If True, display the analysis. If False, do nothing.
    """
    if not show:
        return
    
    print("\n" + "="*70)
    print("OCR ACCURACY ANALYSIS (At the Very Beginning - Before Any Processing)")
    print("="*70)
    
    total_words = len(hypothesis_list)
    words_100_percent = []  # Exact matches (100% fuzzy score)
    words_80_99_percent = []  # 80-99% fuzzy match
    words_less_than_80 = []  # <80% fuzzy match (no candidates)
    
    for hyp in hypothesis_list:
        decoded = text_utils.decode_html_entities(hyp.anchor.content)
        if not hyp.candidates:
            # No candidates = no fuzzy matches above 80% threshold
            words_less_than_80.append(decoded)
        else:
            # Has at least one candidate (exact or fuzzy match)
            best_fuzzy = max((c.fuzzy_score for c in hyp.candidates), default=0.0)
            if best_fuzzy == 100.0:
                words_100_percent.append(decoded)
            elif best_fuzzy >= 80.0:
                words_80_99_percent.append(decoded)
            else:
                words_less_than_80.append(decoded)
    
    count_100 = len(words_100_percent)
    count_80_99 = len(words_80_99_percent)
    count_less_80 = len(words_less_than_80)
    
    pct_100 = count_100 / total_words * 100 if total_words > 0 else 0
    pct_80_99 = count_80_99 / total_words * 100 if total_words > 0 else 0
    pct_less_80 = count_less_80 / total_words * 100 if total_words > 0 else 0
    
    print(f"\nTotal ALTO words: {total_words}")
    print(f"Words with 100% fuzzy match (exact): {count_100} ({pct_100:.1f}%)")
    print(f"Words with 80-99% fuzzy match: {count_80_99} ({pct_80_99:.1f}%)")
    print(f"Words with <80% fuzzy match: {count_less_80} ({pct_less_80:.1f}%)")
    
    print(f"\n{'='*70}")
    print(f"OCR Accuracy (≥80% match): {(pct_100 + pct_80_99):.1f}% ({(count_100 + count_80_99)}/{total_words} words)")
    print(f"{'='*70}\n")

