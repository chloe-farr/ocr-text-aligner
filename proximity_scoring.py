def _is_position_at_edge(position: int, edge_positions: List[int], 
                         typical_edge: int, 
                         specific_tolerance: int = EDGE_MATCH_TOLERANCE_PIXELS,
                         typical_tolerance: int = TYPICAL_EDGE_TOLERANCE_PIXELS) -> Tuple[bool, Optional[int]]:
    """
    Check if a position is at an edge, and return which edge index if found.
    
    Args:
        position: Position to check
        edge_positions: List of specific edge positions
        typical_edge: Typical edge position
        specific_tolerance: Tolerance for matching specific edges
        typical_tolerance: Tolerance for matching typical edge
        
    Returns:
        Tuple of (is_at_edge, edge_index or None)
    """
    # Check specific edge positions
    for i, edge_pos in enumerate(edge_positions):
        if abs(position - edge_pos) < specific_tolerance:
            return True, i
    
    # Check typical edge
    if abs(position - typical_edge) < typical_tolerance:
        # For typical edge, return approximate index
        edge_idx = len(edge_positions) - 1 if edge_positions else 0
        return True, edge_idx
    
    return False, None


def _is_word_at_left_edge(word, column_boundaries: Dict[str, List[int]]) -> Tuple[bool, Optional[int]]:
    """
    Check if a word is at a left edge.
    
    Returns:
        Tuple of (is_at_left_edge, column_index or None)
    """
    word_left_edge = word.hpos
    return _is_position_at_edge(
        word_left_edge,
        column_boundaries['left_edges'],
        column_boundaries['typical_left']
    )


def _is_word_at_right_edge(word, column_boundaries: Dict[str, List[int]], 
                           page=None) -> Tuple[bool, Optional[int]]:
    """
    Check if a word is at a right edge.
    
    Returns:
        Tuple of (is_at_right_edge, column_index or None)
    """
    word_right_edge = word.hpos + word.width
    
    # First check detected edges
    is_at_edge, edge_idx = _is_position_at_edge(
        word_right_edge,
        column_boundaries['right_edges'],
        column_boundaries['typical_right']
    )
    
    if is_at_edge:
        return True, edge_idx
    
    # Fallback: check if near page edge
    if page and word_right_edge > (page.width * PAGE_EDGE_THRESHOLD_RATIO):
        return True, None
    
    return False, None


def _is_word_at_line_end_by_hyphen(word) -> bool:
    """
    Check if word ends with a hyphen character (indicating line end).
    """
    decoded_content = getattr(word, 'content', '')
    return decoded_content.rstrip().endswith(HYPHEN_CHARACTERS)


def _is_word_at_line_end_by_after_word(word, column_boundaries: Dict[str, List[int]]) -> bool:
    """
    Check if word is at line end by examining its after_word position.
    
    This handles cases like "dams" + "aged" = "damaged" where there's no literal hyphen.
    """
    if not (hasattr(word, 'after_word') and word.after_word is not None):
        return False
    
    after_vpos = word.after_word.vpos
    after_hpos = word.after_word.hpos
    word_vpos = word.vpos
    
    # Check if after_word is on a different line
    vpos_diff = abs(word_vpos - after_vpos)
    if vpos_diff <= DIFFERENT_LINE_VPOS_THRESHOLD:
        return False
    
    # Check if after_word is at a detected left edge
    is_at_left, _ = _is_word_at_left_edge(word.after_word, column_boundaries)
    return is_at_left


def is_word_at_right_edge(word, column_boundaries: Dict[str, List[int]], 
                          page=None) -> bool:
    """
    Check if a word is at the right edge of a line/column.
    
    Uses multiple heuristics:
    1. Word ends with hyphen
    2. Word's after_word is on next line at left edge
    3. Word is close to detected right edge positions
    4. Word is near page edge
    
    Returns:
        True if word is at right edge
    """
    # Method 1: Words ending with hyphens
    if _is_word_at_line_end_by_hyphen(word):
        return True
    
    # Method 2: Check if after_word is on next line at left edge
    if _is_word_at_line_end_by_after_word(word, column_boundaries):
        return True
    
    # Method 3: Check detected edges
    is_at_edge, _ = _is_word_at_right_edge(word, column_boundaries, page)
    return is_at_edge


def are_words_in_adjacent_columns(word1, word2, column_boundaries: Dict[str, List[int]]) -> bool:
    """
    Check if two words are in adjacent columns.
    
    Returns True if:
    - word1 is at the right edge of one column AND
    - word2 is at the left edge of the next column
    
    This handles cross-column hyphenation like "sor-" + "ties" where words
    are in different columns but should be linked.
    """
    # Check if word1 is at a right edge
    is_word1_at_right, word1_column_idx = _is_word_at_right_edge(word1, column_boundaries)
    
    # Check if word2 is at a left edge
    is_word2_at_left, word2_column_idx = _is_word_at_left_edge(word2, column_boundaries)
    
    # If both are at edges, check if they're in adjacent columns
    if is_word1_at_right and is_word2_at_left:
        # If column indices are available, check adjacency
        if word1_column_idx is not None and word2_column_idx is not None:
            # Adjacent if word2 is in the next column
            if word2_column_idx == word1_column_idx + 1:
                return True
        
        # Also check if word2 is to the left of word1 (wrapped to next column)
        # This handles cases where exact column indices cannot be determined
        if word2.hpos < word1.hpos:
            return True
    
    return False


