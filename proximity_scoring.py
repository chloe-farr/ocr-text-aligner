def _find_hypothesis_for_word(word, hypothesis_list):
    """
    Find the hypothesis object for a given word.
    
    Args:
        word: Word to find hypothesis for
        hypothesis_list: List of all hypotheses
        
    Returns:
        Hypothesis object or None
    """
    for hyp in hypothesis_list:
        if hyp.anchor == word:
            return hyp
    return None


def _calculate_sequence_score(actual_index: int, expected_index: int) -> float:
    """
    Calculate sequence consistency score.
    
    Args:
        actual_index: Actual LLM token index
        expected_index: Expected LLM token index
        
    Returns:
        Score from 0.0 to 100.0
    """
    if actual_index == expected_index:
        return PERFECT_SEQUENCE_SCORE
    
    # Penalize based on distance from expected position
    distance = abs(actual_index - expected_index)
    return max(0.0, PERFECT_SEQUENCE_SCORE - (distance * SEQUENCE_PENALTY_PER_POSITION))


def _calculate_left_sequence_factor(hypothesis, llm_token_index: int, 
                                     llm_elements: List, hypothesis_list: List) -> Optional[float]:
    """
    Calculate sequence consistency score with left neighbor.
    
    Returns:
        Score from 0.0 to 100.0, or None if not applicable
    """
    if hypothesis.anchor.before_word is None:
        return None
    
    before_hyp = _find_hypothesis_for_word(hypothesis.anchor.before_word, hypothesis_list)
    if not (before_hyp and before_hyp.chosen_LLM_token):
        return None
    
    try:
        before_llm_index = llm_elements.index(before_hyp.chosen_LLM_token)
        expected_index = before_llm_index + 1
        return _calculate_sequence_score(llm_token_index, expected_index)
    except ValueError:
        return None


def _calculate_right_sequence_factor(hypothesis, llm_token_index: int,
                                      llm_elements: List, hypothesis_list: List) -> Optional[float]:
    """
    Calculate sequence consistency score with right neighbor.
    
    Returns:
        Score from 0.0 to 100.0, or None if not applicable
    """
    if hypothesis.anchor.after_word is None:
        return None
    
    after_hyp = _find_hypothesis_for_word(hypothesis.anchor.after_word, hypothesis_list)
    if not (after_hyp and after_hyp.chosen_LLM_token):
        return None
    
    try:
        after_llm_index = llm_elements.index(after_hyp.chosen_LLM_token)
        expected_index = after_llm_index - 1
        return _calculate_sequence_score(llm_token_index, expected_index)
    except ValueError:
        return None


def _calculate_geometric_factor(hypothesis, llm_elements: List, 
                                 hypothesis_list: List) -> Optional[float]:
    """
    Calculate geometric proximity score based on neighbors' positions.
    
    Returns:
        Score from 0.0 to 100.0, or None if not applicable
    """
    if (hypothesis.anchor.before_word is None or 
        hypothesis.anchor.after_word is None):
        return None
    
    before_hyp = _find_hypothesis_for_word(hypothesis.anchor.before_word, hypothesis_list)
    after_hyp = _find_hypothesis_for_word(hypothesis.anchor.after_word, hypothesis_list)
    
    if not (before_hyp and after_hyp and 
            before_hyp.chosen_LLM_token and after_hyp.chosen_LLM_token):
        return None
    
    try:
        # Verify both neighbors have valid LLM tokens in the sequence
        before_llm_index = llm_elements.index(before_hyp.chosen_LLM_token)
        after_llm_index = llm_elements.index(after_hyp.chosen_LLM_token)
        
        # Calculate expected hpos based on interpolation
        before_hpos = before_hyp.anchor.hpos
        after_hpos = after_hyp.anchor.hpos
        expected_hpos = (before_hpos + after_hpos) / 2.0
        
        # Calculate distance from expected position
        actual_hpos = hypothesis.anchor.hpos
        hpos_distance = abs(actual_hpos - expected_hpos)
        
        # Normalize distance
        if hpos_distance < GEOMETRIC_CLOSE_THRESHOLD:
            return PERFECT_SEQUENCE_SCORE
        elif hpos_distance < GEOMETRIC_FAR_THRESHOLD:
            return max(0.0, PERFECT_SEQUENCE_SCORE - 
                      ((hpos_distance - GEOMETRIC_CLOSE_THRESHOLD) / GEOMETRIC_SCORE_DECAY_RATE))
        else:
            return 0.0
    except (ValueError, ZeroDivisionError):
        return None


def _combine_proximity_factors(factors: List[Tuple[str, float]]) -> float:
    """
    Combine proximity scoring factors using weighted average.
    
    Args:
        factors: List of (factor_name, factor_score) tuples
        
    Returns:
        Combined score from 0.0 to 100.0
    """
    if not factors:
        return 0.0
    
    total_weight = 0.0
    weighted_sum = 0.0
    
    for factor_name, factor_score in factors:
        if "sequence" in factor_name:
            weight = SEQUENCE_FACTOR_WEIGHT
        else:
            weight = GEOMETRIC_FACTOR_WEIGHT
        
        weighted_sum += factor_score * weight
        total_weight += weight
    
    if total_weight > 0:
        return weighted_sum / total_weight
    
    return 0.0


