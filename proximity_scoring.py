def _calculate_same_line_distance(hpos1: int, hpos2: int) -> float:
    """
    Calculate distance for words on the same line.
    
    Args:
        hpos1: Horizontal position of first word
        hpos2: Horizontal position of second word
        
    Returns:
        Horizontal distance
    """
    return abs(hpos1 - hpos2)


def _calculate_line_wrap_distance(vpos1: int, vpos2: int) -> float:
    """
    Calculate distance for line wrap (word at end of line, next at start of next line).
    
    Args:
        vpos1: Vertical position of first word
        vpos2: Vertical position of second word
        
    Returns:
        Small penalty for line wrap
    """
    vpos_diff = abs(vpos1 - vpos2)
    return vpos_diff * LINE_WRAP_DISTANCE_MULTIPLIER


def _calculate_column_wrap_distance(hpos1: int, hpos2: int, vpos1: int, vpos2: int) -> float:
    """
    Calculate distance for column wrap (word at right edge, next at left edge of next column).
    
    Args:
        hpos1: Horizontal position of first word
        hpos2: Horizontal position of second word
        vpos1: Vertical position of first word
        vpos2: Vertical position of second word
        
    Returns:
        Moderate distance for column wrap
    """
    vpos_diff = abs(vpos1 - vpos2)
    hpos_diff = abs(hpos1 - hpos2)
    return (vpos_diff * COLUMN_WRAP_VPOS_MULTIPLIER) + (hpos_diff * COLUMN_WRAP_HPOS_MULTIPLIER)


def _calculate_bottom_right_to_top_left_distance(hpos1: int, hpos2: int, vpos1: int, vpos2: int) -> float:
    """
    Calculate distance for bottom-right to top-left wrap (next column, different area).
    
    Args:
        hpos1: Horizontal position of first word
        hpos2: Horizontal position of second word
        vpos1: Vertical position of first word
        vpos2: Vertical position of second word
        
    Returns:
        Distance for bottom-right to top-left wrap
    """
    vpos_diff = abs(vpos1 - vpos2)
    hpos_diff = abs(hpos1 - hpos2)
    return (vpos_diff * COLUMN_WRAP_VPOS_MULTIPLIER) + (hpos_diff * COLUMN_WRAP_HPOS_MULTIPLIER)


def _calculate_default_distance(hpos1: int, hpos2: int, vpos1: int, vpos2: int) -> float:
    """
    Calculate default distance using weighted combination.
    
    Args:
        hpos1: Horizontal position of first word
        hpos2: Horizontal position of second word
        vpos1: Vertical position of first word
        vpos2: Vertical position of second word
        
    Returns:
        Weighted distance (vpos weighted more heavily)
    """
    vpos_diff = abs(vpos1 - vpos2)
    hpos_diff = abs(hpos1 - hpos2)
    return (vpos_diff * DEFAULT_VPOS_MULTIPLIER) + hpos_diff


def calculate_column_aware_threshold(page, column_boundaries: Dict[str, List[int]]) -> float:
    """
    Calculate a column-aware distance threshold for reading order matching.
    
    Uses column boundaries to determine a reasonable maximum distance,
    rather than an arbitrary pixel value.
    
    Returns a threshold that allows up to approximately 2 column heights
    of vertical distance in reading order.
    """
    if page is None:
        return FALLBACK_DISTANCE_THRESHOLD
    
    # Estimate number of columns from detected column boundaries
    num_columns = max(len(column_boundaries['left_edges']), 1)
    
    # Estimate typical column height
    # For multi-column layouts, column height is roughly page height
    # For single column, use page height
    estimated_column_height = page.height
    
    # Allow up to 2x column height in reading order distance
    # This accounts for cases where words might be separated by a column break
    # but are still within reasonable reading order distance
    threshold = estimated_column_height * COLUMN_HEIGHT_MULTIPLIER
    
    return threshold


def calculate_reading_order_distance(word1, word2, page=None, column_boundaries: Optional[Dict[str, List[int]]] = None) -> float:
    """
    Calculate reading order distance between two words, accounting for:
    - Line wrapping (word at end of line, next word at start of next line)
    - Column wrapping (word at right edge, next word at left edge of next column)
    - Bottom-right to top-left wrapping (word at bottom right, next word at top left)
    
    Returns a distance score where lower is better (closer in reading order).
    """
    hpos1, vpos1 = word1.hpos, word1.vpos
    hpos2, vpos2 = word2.hpos, word2.vpos
    
    # Calculate basic differences
    hpos_diff = abs(hpos1 - hpos2)
    vpos_diff = abs(vpos1 - vpos2)
    
    # Get column boundaries (detect if not provided)
    if column_boundaries is None:
        column_boundaries = detect_column_boundaries(page)
    
    # Check edge positions
    is_word1_at_right_edge = is_word_at_right_edge(word1, column_boundaries, page)
    is_word2_at_left_edge, _ = _is_word_at_left_edge(word2, column_boundaries)
    
    # Case 1: Same line (small vpos difference)
    if vpos_diff < SAME_LINE_VERTICAL_THRESHOLD:
        return _calculate_same_line_distance(hpos1, hpos2)
    
    # Case 2: Line wrap in same column
    # Word1 at right edge, word2 at left edge of next line, similar hpos range
    if (is_word1_at_right_edge and is_word2_at_left_edge and 
        vpos_diff < LINE_WRAP_VERTICAL_THRESHOLD and
        hpos_diff < LINE_WRAP_HORIZONTAL_THRESHOLD):
        return _calculate_line_wrap_distance(vpos1, vpos2)
    
    # Case 3: Column wrap
    # Word1 at right edge of one column, word2 at left edge of next column
    # Large hpos difference but word2 has lower hpos (wrapped to next column)
    if (is_word1_at_right_edge and is_word2_at_left_edge and
        hpos2 < hpos1 and  # word2 is to the left (wrapped)
        vpos_diff < COLUMN_WRAP_VERTICAL_THRESHOLD):
        return _calculate_column_wrap_distance(hpos1, hpos2, vpos1, vpos2)
    
    # Case 4: Bottom-right to top-left (next column, different area)
    # Word1 at bottom right, word2 at top left of next column
    if (is_word1_at_right_edge and is_word2_at_left_edge and
        vpos2 < vpos1 and  # word2 is above (wrapped to next column)
        hpos2 < hpos1):  # word2 is to the left
        return _calculate_bottom_right_to_top_left_distance(hpos1, hpos2, vpos1, vpos2)
    
    # Default: Use weighted combination (vpos weighted more heavily)
    return _calculate_default_distance(hpos1, hpos2, vpos1, vpos2)


