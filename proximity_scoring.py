def _collect_page_positions(page) -> Tuple[List[int], List[int]]:
    """
    Collect all left and right positions from page elements.
    
    Returns:
        Tuple of (left_positions, right_positions) lists
    """
    left_positions = []
    right_positions = []
    
    for block in page.content_elements:
        # TextBlock boundaries
        left_positions.append(block.hpos)
        right_positions.append(block.hpos + block.width)
        
        for line in block.content_elements:
            # TextLine boundaries
            left_positions.append(line.hpos)
            right_positions.append(line.hpos + line.width)
            
            # Also check first and last words in each line
            if line.content_elements:
                first_word = line.content_elements[0]
                last_word = line.content_elements[-1]
                left_positions.append(first_word.hpos)
                right_positions.append(last_word.hpos + last_word.width)
    
    return left_positions, right_positions


def _cluster_positions(positions: List[int], tolerance: int = CLUSTER_TOLERANCE_PIXELS) -> List[List[int]]:
    """
    Cluster positions that are within tolerance of each other.
    
    Args:
        positions: Sorted list of positions
        tolerance: Maximum distance for positions to be in same cluster
        
    Returns:
        List of clusters, where each cluster is a list of positions
    """
    if not positions:
        return []
    
    sorted_positions = sorted(positions)
    clusters = []
    current_cluster = [sorted_positions[0]]
    
    for pos in sorted_positions[1:]:
        if pos - current_cluster[-1] < tolerance:
            current_cluster.append(pos)
        else:
            clusters.append(current_cluster)
            current_cluster = [pos]
    clusters.append(current_cluster)
    
    return clusters


def _get_representative_edges(clusters: List[List[int]]) -> List[int]:
    """
    Get representative edge positions from clusters (median of each cluster).
    
    Args:
        clusters: List of position clusters
        
    Returns:
        List of representative edge positions
    """
    edges = []
    for cluster in clusters:
        if len(cluster) > 0:
            sorted_cluster = sorted(cluster)
            median_idx = len(sorted_cluster) // 2
            edges.append(sorted_cluster[median_idx])
    return edges


def _find_typical_position(positions: List[int], fallback: int) -> int:
    """
    Find the most common position in a list.
    
    Args:
        positions: List of positions
        fallback: Value to return if positions list is empty
        
    Returns:
        Most common position, or fallback if no positions
    """
    if not positions:
        return fallback
    counter = Counter(positions)
    return counter.most_common(1)[0][0] if counter else fallback


def detect_column_boundaries(page) -> Dict[str, List[int]]:
    """
    Analyze the page structure to detect column boundaries dynamically.
    
    Returns a dict with:
    - 'left_edges': List of common left edge positions (column starts)
    - 'right_edges': List of common right edge positions (column ends)
    - 'typical_left': Typical left edge position (most common)
    - 'typical_right': Typical right edge position (most common)
    """
    if page is None:
        return {
            'left_edges': FALLBACK_LEFT_EDGES,
            'right_edges': FALLBACK_RIGHT_EDGES,
            'typical_left': FALLBACK_TYPICAL_LEFT,
            'typical_right': FALLBACK_TYPICAL_RIGHT
        }
    
    # Collect all TextBlock and TextLine left/right positions
    left_positions, right_positions = _collect_page_positions(page)
    
    if not left_positions or not right_positions:
        # Fallback to page-based estimates
        return {
            'left_edges': [0, page.width // 2] if page else FALLBACK_LEFT_EDGES,
            'right_edges': [page.width // 2, page.width] if page else FALLBACK_RIGHT_EDGES,
            'typical_left': FALLBACK_TYPICAL_LEFT,
            'typical_right': page.width - 500 if page else FALLBACK_TYPICAL_RIGHT
        }
    
    # Cluster and find representative edges
    left_clusters = _cluster_positions(left_positions)
    right_clusters = _cluster_positions(right_positions)
    
    left_edges = _get_representative_edges(left_clusters)
    right_edges = _get_representative_edges(right_clusters)
    
    # Find most common (typical) positions
    typical_left = _find_typical_position(left_positions, FALLBACK_TYPICAL_LEFT)
    typical_right = _find_typical_position(right_positions, 
                                          page.width - 500 if page else FALLBACK_TYPICAL_RIGHT)
    
    return {
        'left_edges': sorted(set(left_edges)),
        'right_edges': sorted(set(right_edges)),
        'typical_left': typical_left,
        'typical_right': typical_right
    }


